/** Russian plural form: 1 задача / 2 задачи / 5 задач. @param {number} n @param {[string,string,string]} f */
export function ruPlural(n: number, f: [string, string, string]): string {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return f[2];
  if (b > 1 && b < 5) return f[1];
  if (b === 1) return f[0];
  return f[2];
}


